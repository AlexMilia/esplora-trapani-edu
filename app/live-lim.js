/* ------------------------------------------------------------
   RISULTATI (istogramma)
   ------------------------------------------------------------ */
function disegnaRisultati(j) {
  S.fase = 'risultati'; S.rVista = j.q_idx;
  var r = S.root; svuota(r);
  r.appendChild(tacche(j));
  r.appendChild(h('p', { 'class': 'sotto' }, 'Risultati — domanda ' + (j.q_idx + 1)));
  r.appendChild(h('div', { 'class': 'dom' }, j.domanda));

  var max = Math.max.apply(null, j.conta.concat([1]));
  var g = h('div', { 'class': 'griglia' });
  j.opzioni.forEach(function (testo, i) {
    var c = h('div', { 'class': 'cardOpz' +
      (i === j.g ? ' giusta' : (j.conta[i] === 0 ? ' spenta' : '')),
      style: 'background:' + COLORI[i % COLORI.length] });
    var barra = h('div', { 'class': 'barra' });
    c.appendChild(barra);
    var cont = h('div', { 'class': 'cont' });
    cont.appendChild(h('span', { 'class': 'forma' },
      (i === j.g ? '✓ ' : '') + FORME[i % FORME.length]));
    cont.appendChild(h('span', null, testo));
    cont.appendChild(h('span', { 'class': 'n' }, String(j.conta[i])));
    c.appendChild(cont);
    g.appendChild(c);
    setTimeout(function () {
      barra.style.width = Math.round(100 * j.conta[i] / max) + '%';
    }, 60);
  });
  r.appendChild(g);

  var giuste = j.conta[j.g] || 0;
  var frase = j.tot === 0 ? 'Nessuna risposta questa volta!'
    : giuste + ' su ' + j.tot + ' hanno cristallizzato ✨';
  r.appendChild(h('div', { 'class': 'contaR' + (giuste > 0 ? ' brillaL' : '') }, frase));

  if (j.spiegazione) {
    var sap = h('div', { 'class': 'sapevi' });
    if (j.media) sap.appendChild(h('img', { src: j.media, alt: '', loading: 'lazy' }));
    var tx = h('div');
    tx.appendChild(h('div', { 'class': 'tit' }, '🧂 Lo sapevi?'));
    tx.appendChild(h('p', null, j.spiegazione));
    sap.appendChild(tx);
    r.appendChild(sap);
  }

  var ultima = j.q_idx + 1 >= j.n_quiz;
  r.appendChild(h('button', { 'class': 'btn', onclick: avanza },
    ultima ? 'Vediamo com\u2019è andata! →' : 'Prossima domanda →'));
}

/* ------------------------------------------------------------
   FINE (recap di classe — MAI classifica individuale)
   ------------------------------------------------------------ */
function disegnaFine(j) {
  S.fase = 'fine';
  clearInterval(S.timer);
  var r = S.root; svuota(r);
  r.appendChild(h('h2', null, 'Fine del quiz!'));
  r.appendChild(h('p', { 'class': 'pct brillaL' }, j.pct_classe + '%'));
  r.appendChild(h('p', { 'class': 'sotto' },
    'di risposte giuste — tutta la classe insieme (' + j.n_gioc + ' giocatori)'));

  if (S.podio && j.podio && j.podio.length) {
    var MED = ['🥇', '🥈', '🥉'];
    var ORD = j.podio.length === 3 ? [1, 0, 2] : (j.podio.length === 2 ? [1, 0] : [0]);
    var pod = h('div', { 'class': 'podio' });
    ORD.forEach(function (idx) {
      var g = j.podio[idx];
      var gr = h('div', { 'class': 'gr' + (idx === 0 ? ' p1 brillaL' : '') });
      gr.appendChild(h('div', { 'class': 'med' }, MED[idx]));
      gr.appendChild(h('div', { 'class': 'nm' }, g.nome));
      gr.appendChild(h('div', { 'class': 'pt' }, g.giuste + ' su ' + j.n_quiz));
      pod.appendChild(gr);
    });
    r.appendChild(pod);
  }

  var rec = h('div', { 'class': 'recap' });
  (j.recap || []).forEach(function (q, i) {
    var riga = h('div', { 'class': 'recapR' });
    riga.appendChild(h('span', null, (i + 1) + '. ' + q.domanda));
    riga.appendChild(h('span', { 'class': 'rp',
      style: 'color:' + (q.pct >= 60 ? '#2f7a46' : '#b8506a') }, q.pct + '%'));
    rec.appendChild(riga);
  });
  r.appendChild(rec);

  r.appendChild(h('p', { 'class': 'sotto', style: 'margin-top:16px' },
    'Il sale si ricristallizza sempre: quello che oggi si scioglie, domani brilla. ✨'));
  r.appendChild(h('button', { 'class': 'btn oro', onclick: function () {
    finisci(j);
  } }, 'Chiudi il quiz live'));
}

function finisci(j) {
  var dettaglio = {
    live: true,
    lezione: (S.cfg && S.cfg.lezione) || '',
    livello: (S.cfg && S.cfg.livello) || '',
    pct_classe: j.pct_classe, n_gioc: j.n_gioc, n_quiz: j.n_quiz,
    recap: (j.recap || []).map(function (q) { return { pct: q.pct, tot: q.tot }; })
  };
  post('chiudi', { pin: S.pin, host: S.host }).catch(function () {});
  try {
    document.dispatchEvent(new CustomEvent('edu-live-fine', { detail: dettaglio }));
  } catch (e) {}
  if (S.cfg && typeof S.cfg.onFine === 'function') {
    try { S.cfg.onFine(dettaglio); } catch (e) {}
  }
  chiudiTutto();
}

