function aggiornaLobby(j) {
  var pinEl = S.root.querySelector('.pin');
  if (pinEl && S.pin) pinEl.textContent = S.pin.split('').join(' ');

  var qrEl = document.getElementById('elQr');
  if (qrEl && !qrEl.firstChild && S.pin && typeof qrcode === 'function') {
    try {
      var qr = qrcode(0, 'M');
      qr.addData(S.urlRispondi + '?pin=' + S.pin);
      qr.make();
      qrEl.innerHTML = qr.createImgTag(6, 8);
    } catch (e) { qrEl.textContent = ''; }
  }

  var ng = document.getElementById('elNg');
  if (ng) ng.textContent = j.n_gioc === 0 ? 'Aspetto i giocatori…'
    : j.n_gioc + (j.n_gioc === 1 ? ' giocatore pronto' : ' giocatori pronti');

  var chips = document.getElementById('elChips');
  if (chips) {
    chips.innerHTML = '';
    (j.nomi || []).forEach(function (g) {
      chips.appendChild(h('button', { 'class': 'chip', onclick: function () {
        if (confirm('Vuoi far uscire "' + g.nome + '"?'))
          post('rimuovi', { pin: S.pin, host: S.host, giocatore: g.t });
      } }, g.nome));
    });
  }
  var via = document.getElementById('elVia');
  if (via) via.disabled = j.n_gioc === 0;
}

