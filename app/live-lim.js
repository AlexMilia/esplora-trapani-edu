function avanza() {
  post('avanza', { pin: S.pin, host: S.host }).then(function () { giro(); });
}
function chiudiConferma() {
  if (S && S.fase && S.fase !== 'fine' && S.fase !== 'attesa') {
    if (!confirm('Vuoi davvero interrompere il quiz live?')) return;
  }
  if (S && S.pin) post('chiudi', { pin: S.pin, host: S.host }).catch(function () {});
  chiudiTutto();
}
function chiudiTutto() {
  if (S && S.timer) clearInterval(S.timer);
  var r = document.getElementById('eduLive');
  if (r) r.remove();
  S = null;
}

window.EduLive = { apri: apri, chiudi: chiudiConferma };
